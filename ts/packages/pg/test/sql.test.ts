import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import type { Pool } from 'pg'
import { createDb } from '@eqts/core'
import { Gadget, schema, User } from '@eqts/test/fixture'
import { postgres } from '../src/index.ts'

describe('postgres: SQL text', () => {
  const db = createDb({ schema, adapter: postgres({} as Pool) })

  it('numbers placeholders and keeps booleans', () => {
    const s = db.queryable(User).where((u) => [u.name.eq('a'), u.age.in([1, 2])]).select((u) => ({ id: u.id })).toSQL()
    assert.equal(s.sql, 'SELECT t0."id" AS "c0" FROM "t_user" t0 WHERE t0."name" = $1 AND t0."age" IN ($2, $3)')
    assert.equal(db.queryable(User).where((u) => u.id.eq(1)).toSQL().params.length, 1)
  })
})

describe('postgres: code-first DDL', () => {
  const db = createDb({ schema, adapter: postgres({ query: async () => ({ rows: [] }) } as unknown as Pool) })

  it('renders CREATE TABLE with PG types and an identity column', () => {
    assert.equal(db.createTableSql(Gadget), 'CREATE TABLE IF NOT EXISTS "t_gadget" ("id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL, "name" VARCHAR(50) NOT NULL, "price" NUMERIC(10, 2) NOT NULL,'
      + ' "qty" INTEGER NOT NULL DEFAULT 0, "active" BOOLEAN NOT NULL, "born" DATE, "seen_at" TIMESTAMP(3) NOT NULL, "tags" JSONB NOT NULL, "photo" BYTEA, PRIMARY KEY ("id"), UNIQUE ("name"))')
  })
})
