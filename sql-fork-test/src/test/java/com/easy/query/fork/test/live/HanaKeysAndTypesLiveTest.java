package com.easy.query.fork.test.live;

import com.easy.query.api.proxy.client.EasyEntityQuery;
import com.easy.query.fork.test.entity.ForkAutoId;
import org.junit.Assert;
import org.junit.Before;
import org.junit.Test;

import java.time.LocalDateTime;
import java.util.Arrays;
import java.util.List;

/** M2b：HANA 上的生成键回填与时间的读写（-Plive）。 */
public class HanaKeysAndTypesLiveTest {
    private final LiveDatabases.Live live = LiveDatabases.hana();
    private EasyEntityQuery db;

    @Before
    public void seed() {
        live.executeIgnoring("DROP TABLE \"t_fork_auto\"");
        live.execute("CREATE COLUMN TABLE \"t_fork_auto\" (\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \"name\" NVARCHAR(100), \"at\" TIMESTAMP)");
        db = live.client();
    }

    private static ForkAutoId row(String name, LocalDateTime at) {
        ForkAutoId r = new ForkAutoId();
        r.setName(name);
        r.setAt(at);
        return r;
    }

    @Test
    public void generatedKeyIsFilledBack() {
        ForkAutoId one = row("a", LocalDateTime.of(2026, 10, 28, 1, 2, 3));
        Assert.assertEquals(1L, db.insertable(one).executeRows(true));
        Assert.assertNotNull("generated id", one.getId());
        Assert.assertEquals("a", db.queryable(ForkAutoId.class).whereById(one.getId()).singleNotNull().getName());
    }

    @Test
    public void generatedKeysForBatch() {
        List<ForkAutoId> rows = Arrays.asList(row("b", null), row("c", null), row("d", null));
        Assert.assertEquals(3L, db.insertable(rows).executeRows(true));
        for (ForkAutoId r : rows) {
            Assert.assertNotNull("generated id for " + r.getName(), r.getId());
            Assert.assertEquals(r.getName(), db.queryable(ForkAutoId.class).whereById(r.getId()).singleNotNull().getName());
        }
    }

    /**
     * 2026-03-29 02:30 在柏林是夏令时跳过的时刻：经 java.sql.Timestamp 按 JVM 时区换算的驱动路径会把它挪成 03:30。
     * LocalDateTime 列不带时区，存进去什么就要读回什么。
     */
    @Test
    public void localDateTimeSurvivesDstGapOfJvmZone() {
        java.util.TimeZone original = java.util.TimeZone.getDefault();
        java.util.TimeZone.setDefault(java.util.TimeZone.getTimeZone("Europe/Berlin"));
        try {
            LocalDateTime gap = LocalDateTime.of(2026, 3, 29, 2, 30, 0);
            ForkAutoId one = row("dst", gap);
            db.insertable(one).executeRows(true);
            Assert.assertEquals(gap, db.queryable(ForkAutoId.class).whereById(one.getId()).singleNotNull().getAt());
        } finally {
            java.util.TimeZone.setDefault(original);
        }
    }

    @Test
    public void localDateTimeRoundTrip() {
        LocalDateTime at = LocalDateTime.of(2026, 3, 29, 2, 30, 0, 123_456_700);
        ForkAutoId one = row("t", at);
        db.insertable(one).executeRows(true);
        Assert.assertEquals(at, db.queryable(ForkAutoId.class).whereById(one.getId()).singleNotNull().getAt());
    }
}
